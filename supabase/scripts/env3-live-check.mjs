#!/usr/bin/env node
// ENV-3 · LIVE half — generates the ledger comparison, it does not run it.
//
// The static guard (check-migration-manifest.mjs) proves the declaration is
// coherent with the tree. This one closes the contract by bringing in the third
// term — the ledger itself:
//
//   authored  migration files in supabase/migrations/
//   declared  supabase/expected_applied.json, per environment
//   observed  supabase_migrations.schema_migrations, on the live database
//
// It emits a single self-rolling-back DO block on stdout. The caller
// (live-evidence.sh) feeds that to psql against QA. Generating SQL rather than
// parsing CLI table output keeps the comparison IN the database, where set
// arithmetic is exact, and keeps this file testable offline against any
// throwaway Postgres.
//
// WHAT IT IS NOT: it is not "ledger max == highest migration filename". That
// predicate was ruled architecturally wrong — a max cannot see a hole, it
// asserts authored == applied (which 102 and 123 violate deliberately), and it
// is environment-blind. The contract here is directional: divergence is fatal
// only when it is UNDECLARED.
//
//   node supabase/scripts/env3-live-check.mjs [--env qa] > /tmp/env3.sql
//
// Exits non-zero only if the declaration itself cannot be read; the SQL it
// prints is what decides pass or fail, and it does so on the live ledger.

import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = join(HERE, '..', 'migrations');
const MANIFEST = join(HERE, '..', 'expected_applied.json');
const envArg = process.argv.indexOf('--env');
const ENV = envArg !== -1 && process.argv[envArg + 1] ? process.argv[envArg + 1] : 'qa';

const authored = readdirSync(MIGRATIONS_DIR)
  .filter((f) => /^\d{3}_[a-z0-9_]+\.sql$/.test(f))
  .map((f) => f.slice(0, 3))
  .sort();

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const decl = manifest.environments?.[ENV];
if (!decl) {
  console.error(`FAIL — ${MANIFEST} declares no environment "${ENV}".`);
  process.exit(1);
}
const frontier = decl.applied_through;
const excluded = Object.keys(decl.excluded || {});
const pending = Object.keys(decl.pending || {}).sort();
const expected = authored.filter((v) => v <= frontier && !excluded.includes(v));

const arr = (xs) => (xs.length ? xs.map((v) => `'${v}'`).join(', ') : `NULL::text`);
const lit = (s) => String(s).replace(/'/g, "''");

process.stdout.write(`-- GENERATED by supabase/scripts/env3-live-check.mjs — do not edit, do not commit.
-- environment: ${ENV} · frontier: ${frontier} · authored: ${authored.length} · expected: ${expected.length}
-- pending (declared, NOT a failure): ${pending.length ? pending.join(', ') : '(none)'}
--
-- Read-only: one DO block that ends by RAISEing its report, so the transaction
-- always rolls back. It writes nothing and reads only the ledger catalogue.
do $$
declare
  v_res      text := '';
  v_n        int;
  v_list     text;
  v_expected text[] := ARRAY[${arr(expected)}];
  v_authored text[] := ARRAY[${arr(authored)}];
  v_pending  text   := '${lit(pending.join(', ') || '(none)')}';
  v_min      text;
  v_max      text;
begin
  if to_regclass('supabase_migrations.schema_migrations') is null then
    raise exception E'\\n=== ENV-3 LEDGER (${lit(ENV)}) ===\\nFAIL L-0  supabase_migrations.schema_migrations does not exist on this target.';
  end if;

  -- L-1 · declared-and-expected, but NOT in the ledger.
  --      The original ENV-3 defect: ten rows applied and unrecorded.
  select count(*), coalesce(string_agg(v, ', ' order by v), '—') into v_n, v_list
    from unnest(v_expected) v
   where not exists (select 1 from supabase_migrations.schema_migrations m where m.version = v);
  v_res := v_res || case when v_n = 0 then 'PASS' else 'FAIL' end
    || ' L-1  expected migrations missing from the ledger: ' || v_n || ' — ' || v_list || E'\\n';

  -- L-2 · in the ledger, but NOT declared for this environment.
  --      Catches an out-of-band apply — including a premature 123.
  select count(*), coalesce(string_agg(m.version, ', ' order by m.version), '—') into v_n, v_list
    from supabase_migrations.schema_migrations m
   where not (m.version = any(v_expected));
  v_res := v_res || case when v_n = 0 then 'PASS' else 'FAIL' end
    || ' L-2  applied but undeclared: ' || v_n || ' — ' || v_list || E'\\n';

  -- L-3 · in the ledger with no migration file behind it.
  --      History rewritten, or a migration deleted.
  select count(*), coalesce(string_agg(m.version, ', ' order by m.version), '—') into v_n, v_list
    from supabase_migrations.schema_migrations m
   where not (m.version = any(v_authored));
  v_res := v_res || case when v_n = 0 then 'PASS' else 'FAIL' end
    || ' L-3  stale ledger rows (no authored migration): ' || v_n || ' — ' || v_list || E'\\n';

  -- L-4 · holes in what is actually applied, between its own bounds.
  select min(version), max(version) into v_min, v_max from supabase_migrations.schema_migrations;
  select count(*), coalesce(string_agg(v, ', ' order by v), '—') into v_n, v_list
    from unnest(v_authored) v
   where v > v_min and v < v_max
     and not exists (select 1 from supabase_migrations.schema_migrations m where m.version = v);
  v_res := v_res || case when v_n = 0 then 'PASS' else 'FAIL' end
    || ' L-4  holes in the applied sequence (' || coalesce(v_min,'—') || '-' || coalesce(v_max,'—')
    || '): ' || v_n || ' — ' || v_list || E'\\n';

  -- L-5 · drift summary. Equal cardinality is necessary, never sufficient —
  --       L-1..L-3 are what actually decide it.
  select count(*) into v_n from supabase_migrations.schema_migrations;
  v_res := v_res || case when v_n = array_length(v_expected, 1) then 'PASS' else 'FAIL' end
    || ' L-5  ledger rows ' || v_n || ' vs declared expected '
    || coalesce(array_length(v_expected, 1), 0) || E'\\n';

  -- INFO · authored but deliberately not applied here. NEVER a failure, and
  --        never written into the ledger to make this check green: a row
  --        inserted ahead of the migration makes a later db push skip it.
  v_res := v_res || 'INFO authored and PENDING for ${lit(ENV)} (declared, not applied): ' || v_pending || E'\\n';

  raise exception E'\\n=== ENV-3 LEDGER (${lit(ENV)}) ===\\n%', v_res;
end;
$$;
`);
